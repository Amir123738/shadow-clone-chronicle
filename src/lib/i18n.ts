export const TRANSLATIONS: Record<Lang, Dict> = { en, ru, kk, uk, tr, de, ko, zh, mn };

export function makeT(lang: Lang) {
  return (k: string, vars?: Record<string, string | number>) => {
    let s = TRANSLATIONS[lang]?.[k] ?? TRANSLATIONS.en[k] ?? k;
    if (vars) for (const [k2, v] of Object.entries(vars)) s = s.replaceAll(`{${k2}}`, String(v));
    return s;
  };
}
